 -- [dbo].[getCSSTableForProjects]  '01/01/2023' , '03/31/2023', null
CREATE PROCEDURE [dbo].[getCSSTableForProjects]  
@startDate Date,
@endDate Date,
@projIds varchar(max) =NULL
AS  
BEGIN   
 
 SELECT 
 ID,SURVEY_ID,PROJECT_ID,PROJECT_NAME,CUSTOMER_ID,CUSTOMER_Name,CSM_EMP_ID,DELIVERY_HEAD_EMP_ID,RESPONDENT_NAME,CSAT_RECIEVED_DATE,YEAR_QUARTER,REGION,RESPONSIVENESS,NPS_SCORE,COMMENTS 
 ,Q1,Q2,Q3,Q4,Q5,Q6,Q7,Q8,Q9,Q10,Q11,Q12,Q13,Q14,Q15 
 , CASE WHEN Q1 IS NULL THEN (CASE WHEN Q8 IS NULL THEN  (Q5+Q6+Q7)/3   ELSE ((Q8+Q9+Q10+Q11+Q12)/5) END ) ELSE (Q1+Q2+Q3)/3 END AS  [MIN_SCORE]    --, IIF(OVERALL_QUALITY_OF_DELIVERABLE<ENABLING_SUCCESS,IIF (OVERALL_QUALITY_OF_DELIVERABLE < VALUE_ADDS,OVERALL_QUALITY_OF_DELIVERABLE, VALUE_ADDS),IIF (ENABLING_SUCCESS < VALUE_ADDS,ENABLING_SUCCESS, VALUE_ADDS)) [MIN_SCORE]  
 FROM   
 (  
 SELECT   
  0 ID,vw.SURVEY_ID, CB.PROJ_ID [PROJECT_ID],p.PROJ_NM [PROJECT_NAME], CB.CUST_ID [CUSTOMER_ID],C.CUST_NM [CUSTOMER_Name], P.PROJ_DM_EMP_ID [CSM_EMP_ID], P.PROJ_BUHEAD_EMP_ID [DELIVERY_HEAD_EMP_ID]  
  , CB.DISPLAY_NAME RESPONDENT_NAME, SURVEY_RECEIVED_DATE [CSAT_RECIEVED_DATE], 'Q' + CAST(B.SEQUENCE AS VARCHAR) + ' ' + CAST(B.YEAR AS VARCHAR) + '-' + CAST(B.YEAR - 1999 AS VARCHAR) YEAR_QUARTER  
  , CASE WHEN P.PROJ_ID LIKE '201%' THEN 'India' WHEN P.PROJ_ID LIKE '202%' THEN 'US' WHEN P.PROJ_ID LIKE '206%' THEN 'Oman' WHEN P.PROJ_ID LIKE '207%' THEN 'Dubai' WHEN P.PROJ_ID LIKE '209%' THEN 'Saudi Arabia' ELSE '' END AS REGION  
