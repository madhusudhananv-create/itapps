  , Q4 AS [NPS_SCORE]   
  ,Q1,Q2,Q3,Q4,Q5,Q6,Q7,Q8,Q9,Q10,Q11,Q12,Q13,Q14,Q15  
   ,CASE WHEN Q1 IS NULL THEN (SELECT TOP 1 RATING_DESCRIPTION FROM CSS_QUESTION_REPLIES R (NOLOCK) WHERE CB.ID = R.BATCH_CUSTOMER_ID AND QUESTION_ID = 15) ELSE (SELECT TOP 1 RATING_DESCRIPTION FROM CSS_QUESTION_REPLIES R (NOLOCK) WHERE CB.ID = R.BATCH_CUSTOMER_ID AND QUESTION_ID = 5)  END  AS [COMMENTS]  
  FROM [CSS_BATCH_CUSTOMERS] CB (NOLOCK)  
  INNER JOIN PROJECT P (NOLOCK) on p.proj_id = CB.proj_id  
  INNER JOIN CUSTOMER C (NOLOCK) on c.cust_id = CB.cust_id  
  INNER JOIN CSS_BATCHES B (NOLOCK) ON B.ID = CB.BATCH_ID  
  INNER JOIN vwSurveyQRatings vw ON vw.ID = CB.SURVEY_ID
  WHERE CB.STATUS = 'COMPLETED' AND 
  (B.START_DATE between @startDate AND @endDate
  OR B.END_DATE  between @startDate AND @endDate)
  AND ( ISNULL(@projIds ,'')='' OR CB.proj_id in (SELECT * FROM [DBO].[FN_SPLITSTRING](@projIds,',')))  

  UNION ALL

  SELECT   
  0 ID, vw.SURVEY_ID,p.proj_id [PROJECT_ID],'Premier Healthcare Solutions' [PROJECT_NAME], CB.CUST_ID [CUSTOMER_ID],C.CUST_NM [CUSTOMER_Name],'' [CSM_EMP_ID], '' [DELIVERY_HEAD_EMP_ID]  
