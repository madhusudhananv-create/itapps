INNER JOIN KPI K (NOLOCK) ON K.ID = KD.KPI_ID AND K.ISACTIVE = 1    
INNER JOIN KPI_GOALS GOALS  (NOLOCK) ON GOALS.ID = K.GOAL_ID AND GOALS.ISACTIVE = 1     
INNER JOIN PROJECT P  (NOLOCK) ON P.PROJ_ID = K.PROJECT_ID             
INNER JOIN CUSTOMER C  (NOLOCK) ON C.CUST_ID = K.CUSTOMER_ID             
INNER JOIN GLOBAL_KPI_CATEGORY GKC (NOLOCK)  ON K.GLOBAL_KPI_CATEGORY_ID = GKC.ID            
WHERE PERIOD BETWEEN @START_DATE AND @END_DATE AND KD.ISFLAG=0  AND KD.ISACTIVE =1  and isnull(p.PROJ_STATUS,'') != 'Close' 
AND (ISNULL(@PROJIDS,'')='' OR K.PROJECT_ID IN (SELECT * FROM [DBO].[FN_SPLITSTRING](@PROJIDS,',')))
ORDER BY C.CUST_NM, P.PROJ_NM    
END    

GO

