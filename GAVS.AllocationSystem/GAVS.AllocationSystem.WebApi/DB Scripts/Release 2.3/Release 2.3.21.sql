 -- , '' [COMMENTS]  
  FROM [CSS_BATCH_CUSTOMER_MONTHLY] CB (NOLOCK)  
  INNER JOIN PROJECT P (NOLOCK) on p.proj_id   in ((SELECT top 1 PROJ_ID FROM PROJECT
