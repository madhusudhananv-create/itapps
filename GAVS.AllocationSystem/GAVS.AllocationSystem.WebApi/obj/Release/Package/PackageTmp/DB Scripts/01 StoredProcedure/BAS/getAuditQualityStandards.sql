USE BAS
GO

IF EXISTS(SELECT 1 FROM sys.procedures WHERE name ='getAuditQualityStandards' AND TYPE='P')
BEGIN
       DROP PROCEDURE [dbo].getAuditQualityStandards
END
GO

CREATE Procedure getAuditQualityStandards

As  
Begin

Select E.EMP_ID,E.FRST_NM,
PROCESS_MODEL_ID = STUFF((SELECT ',' + convert(varchar(10),AQ.QUALIFIED_STANDARDS) FROM AUDITOR_QUALIFIED_STANDARDS AQ   
inner join PROCESS_MODEL PM on PM.ID = AQ.QUALIFIED_STANDARDS   
where AQ.EMP_ID = E.EMP_ID and AQ.ISACTIVE=1 order by PM.TITLE FOR XML PATH('')), 1, 1, ''),
PROCESS_MODEL = STUFF((SELECT ', ' + PM.TITLE FROM AUDITOR_QUALIFIED_STANDARDS AQ   
inner join PROCESS_MODEL PM on PM.ID = AQ.QUALIFIED_STANDARDS   
where AQ.EMP_ID = E.EMP_ID and AQ.ISACTIVE=1 order by 1 FOR XML PATH('')), 1, 1, ''),
EFFECTIVE_FROM = (Select top 1 EFFECTIVE_FROM from AUDITOR_QUALIFIED_STANDARDS AQ inner join PROCESS_MODEL PM on PM.ID = AQ.QUALIFIED_STANDARDS where AQ.EMP_ID = E.EMP_ID and AQ.ISACTIVE=1)
from  EMP_INFO E where E.CSM_TITLE_ID=7 and DOR IS NULL and EMP_ID not like '900%' order by E.FRST_NM,PROCESS_MODEL

end
Go
