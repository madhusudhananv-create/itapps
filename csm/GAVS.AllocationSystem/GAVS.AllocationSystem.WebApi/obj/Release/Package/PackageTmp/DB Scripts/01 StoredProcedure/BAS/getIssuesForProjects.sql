USE BAS
GO

IF EXISTS(SELECT 1 FROM sys.procedures WHERE name ='getIssuesForProjects' AND TYPE='P')
BEGIN
DROP PROCEDURE getIssuesForProjects          
END
GO

CREATE procedure [dbo].[getIssuesForProjects]  
@startDate Date,
@EndDate Date,
@PROJIDS VARCHAR(MAX) 

as                
begin                 
select I.ID, PROJECT_ID, RAG, DESCRIPTION, IMPACT_SUMMARY, IS_POTENTIAL_RISK, BUSINESS_IMPACT, GEO_LOCATION, ISSUE_TYPE, SEVERITY, ACTION_PLAN,                
ASSIGNED_TO,IDENTIFIED_BY,REPORTED_BY, LEVEL, IDENTIFIED_DATE, TARGET_DATE, STATUS, ISSUE_RESOLVED_DATE, I.COMMENTS,                
I.CREATED_BY, I.CREATED_DATE, I.UPDATED_BY, I.UPDATED_DATE, I.ISACTIVE,                
P.CUST_ID, PP.PORTFOLIO_ID, PF.TITLE AS PORTFOLIO_NM, P.PROJ_NM             
FROM PROJECT_ISSUE I (NOLOCK)             
INNER JOIN PROJECT P (NOLOCK) ON I.PROJECT_ID = P.PROJ_ID and P.PROJ_ID IN (SELECT * FROM [DBO].[FN_SPLITSTRING](@PROJIDS,',')) AND  I.ISACTIVE =1                    
LEFT OUTER JOIN PORTFOLIO_PROJECT PP (NOLOCK) ON PP.PROJ_ID = P.PROJ_ID                
LEFT OUTER JOIN PORTFOLIO PF (NOLOCK)  ON PF.ID = PP.PORTFOLIO_ID   
WHERE I.IDENTIFIED_DATE BETWEEN @startDate AND @EndDate
OR  I.CREATED_DATE BETWEEN @startDate AND @EndDate
OR  I.ISSUE_RESOLVED_DATE BETWEEN @startDate AND @EndDate
ORDER BY I.IDENTIFIED_DATE DESC               

end   