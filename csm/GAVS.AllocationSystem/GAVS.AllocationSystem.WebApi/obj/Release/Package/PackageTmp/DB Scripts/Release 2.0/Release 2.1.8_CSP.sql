    left outer join    portfolio_project pp on p.PROJ_ID = pp.PROJ_ID
   inner join PORTFOLIO por on pp.PORTFOLIO_ID = por.ID
   WHERE P.END_DATE > @STARTDATE AND PROJ_NM NOT LIKE 'INT-%' AND P.CUST_ID not in (0,201100010, 202100062,202100091 ) AND P.PROJ_ID = PARENT_PROJ_ID   and isnull( p.PROJ_STATUS,'') !='close'  
     
ORDER BY CSP.NEED_FOCUS desc, CSP.HR_NEED_FOCUS desc, CUST_NM, PROJ_NM  END

