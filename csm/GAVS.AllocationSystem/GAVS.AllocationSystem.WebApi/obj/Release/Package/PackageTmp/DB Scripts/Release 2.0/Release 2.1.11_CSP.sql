CREATE function dbo.getminutes(  @value decimal(10,2),  @uom int)
returns decimal(10,2)
as
BEGIN
    if(@uom = 1)
        return @value
    else if (@uom = 2)
        return @value * 60
    else if(@uom = 3)
        return @value * 60 * 8

    return @value

END

