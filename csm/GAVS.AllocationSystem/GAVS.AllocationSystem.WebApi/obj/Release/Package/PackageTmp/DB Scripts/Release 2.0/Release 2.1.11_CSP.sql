CREATE PROCEDURE [dbo].[getProcessByServiceArea]        
@SERVICE_AREA_ID int        
        
AS        
BEGIN           
select distinct pm.ID as PROCESS_MODEL_ID, pm.title PROCESS_MODEL_TITLE, P.PROCESS_AREA_ID, PA.TITLE PROCESS_AREA_TITLE        
, PROCESS_ID, P.TITLE PROCESS_TITLE, P.DESCRIPTION PROCESS_DESCRIPTION from PROCESS_MODEL pm  
inner join PROCESS_MODEL_PROCESS_MAPPING map on map.PROCESS_MODEL_ID = pm.ID and map.ISACTIVE = 1 and map.ISACTIVE =1   
inner join process p on p.ID = map.PROCESS_ID and p.ISACTIVE = 1  
inner join PROCESS_AREA pa on pa.ID = p.PROCESS_AREA_ID and pa.ISACTIVE = 1  
WHERE p.ID IN(SELECT PROCESS_ID FROM PROCESS_SERVICE_AREA_MAPPING    
WHERE SERVICE_AREA_ID = @SERVICE_AREA_ID   AND ISACTIVE = 1  )  
        
END
