CREATE procedure        
getallassessment        
@custid int,        
@startdate datetime,        
@enddate datetime        
as        
begin        
 select t.*, c.CUST_NM, p.PROJ_NM  ,(select top 1 FRST_NM from bas..EMP_INFO e where e.emp_id = t.OWNER) AS 'OWNER_NAME',      
 (select top 1 FRST_NM from bas..EMP_INFO e where e.emp_id = t.ASSIGNED_TO) AS 'ASSIGNED_TO_NAME'      
  from task t        
 inner join bas..CUSTOMER c on t.CUST_ID = c.CUST_ID and t.CUST_ID = @custid        
 inner join bas..PROJECT p on p.PROJ_ID = t.PROJ_ID        
       
 where t.SCHEDULED_START_DATE >= @startdate and t.SCHEDULED_START_DATE <= @enddate   
 and t.TASK_CATEGORY_ID in (select OPTIONS from PARAMETER_TABLE where NAME ='AUDIT_CATEGORY')  
 and t.ISACTIVE = 1        
end       
