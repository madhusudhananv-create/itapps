USE BAS
GO
IF EXISTS(SELECT 1 FROM sys.procedures WHERE name ='getMonthActionItems' AND TYPE='P')
BEGIN
DROP PROCEDURE getMonthActionItems          
END
GO
  
CREATE PROCEDURE [dbo].[getMonthActionItems]                
 @ProjIds VARCHAR(MAX)   
 AS  
 BEGIN  
 DECLARE @fromDate date= Dateadd(Month, Datediff(Month, 0, DATEADD(m, -6, current_timestamp)), 0); 
 SELECT  DATENAME(MM,A.COMPLETION_DATE) AS MONTH_NAME,COUNT(A.STATUS) AS STATUS                
 FROM [PROJECT_ACTIONITEM] A  (NOLOCK)              
    INNER JOIN PROJECT P   (NOLOCK) ON a.PROJECT_ID = p.PROJ_ID AND   
 P.PROJ_ID IN (SELECT * FROM [DBO].[FN_SPLITSTRING](@PROJIDS,','))  AND A.ISACTIVE = 1           
 and A.STATUS = 'Completed' and A.COMPLETION_DATE >= DATEADD(M,-6,GETDATE())  
 LEFT OUTER JOIN PORTFOLIO_PROJECT PP  (NOLOCK) ON PP.PROJ_ID =  A.PROJECT_ID                
 LEFT OUTER JOIN PORTFOLIO PF  (NOLOCK) ON PF.ID = PP.PORTFOLIO_ID       
  WHERE A.COMPLETION_DATE BETWEEN @fromDate AND GETDATE()
    group by DATENAME(MM,A.COMPLETION_DATE)  
 ORDER BY DATENAME(MM,A.COMPLETION_DATE)  
    
 END  
  