			ROUND((CASE WHEN BEFORE_TIME_TAKEN_UOM = 1 THEN ((BEFORE_TIME_TAKEN / 60) * BEFORE_OCCOURANCE_COUNT * BEFORE_FTECOST_HOUR)
				  WHEN BEFORE_TIME_TAKEN_UOM = 2 THEN (BEFORE_TIME_TAKEN * BEFORE_OCCOURANCE_COUNT * BEFORE_FTECOST_HOUR)
