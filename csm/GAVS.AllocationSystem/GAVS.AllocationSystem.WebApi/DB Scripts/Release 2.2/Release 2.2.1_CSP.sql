	  ELSE
		SET @BEFORE_FTE_SPENT_YEAR = 0

	IF @AFTER_FTECOST_MONTH > 0
		SET @AFTER_FTE_SPENT_YEAR = @AFTER_EFFORT_YEAR / @AFTER_FTECOST_MONTH
	ELSE
		SET @AFTER_FTE_SPENT_YEAR = 0

	INSERT INTO BENEFIT_DETAILS_QUANTITATIVE
			(
			[BENEFIT_SUMMARY_ID],
			[UOM_ID],
			[CURRENT_STATE_MONTH],
			[CURRENT_STATE_YEAR],
			[FUTURE_STATE_MONTH],
			[FUTURE_STATE_YEAR],
