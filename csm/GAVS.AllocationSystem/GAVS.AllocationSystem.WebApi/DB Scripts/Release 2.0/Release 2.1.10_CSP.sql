CREATE PROCEDURE [dbo].[getProcessByServiceArea]        
@SERVICE_AREA_ID int        
        
AS        
BEGIN           
;        
WITH PMIDS AS (        
SELECT DISTINCT PM.ID, PM.TITLE FROM PROCESS_MODEL_PROCESS_MAPPING  MP      
INNER JOIN PROCESS_MODEL PM ON PM.ID = PROCESS_MODEL_ID     and pm.ISACTIVE =1  AND MP.ISACTIVE =1  
WHERE PROCESS_ID IN(SELECT PROCESS_ID FROM PROCESS_SERVICE_AREA_MAPPING    
WHERE SERVICE_AREA_ID = @SERVICE_AREA_ID    and ISACTIVE =1    
) )        
    
        
SELECT distinct PROCESS_MODEL_ID, PM.TITLE PROCESS_MODEL_TITLE        
, P.PROCESS_AREA_ID, PA.TITLE PROCESS_AREA_TITLE        
, PROCESS_ID, P.TITLE PROCESS_TITLE, P.DESCRIPTION PROCESS_DESCRIPTION        
FROM PROCESS_MODEL_PROCESS_MAPPING MP        
INNER JOIN PROCESS_MODEL PM ON PM.ID = PROCESS_MODEL_ID AND MP.ISACTIVE =1 AND PM.ISACTIVE =1  
INNER JOIN PROCESS P ON PROCESS_ID = P.ID  AND P.ISACTIVE =1       
INNER JOIN PROCESS_AREA PA ON PA.ID = P.PROCESS_AREA_ID AND PA.ISACTIVE =1  
WHERE  PROCESS_MODEL_ID IN (SELECT ID FROM PMIDS)        
     
        
END
