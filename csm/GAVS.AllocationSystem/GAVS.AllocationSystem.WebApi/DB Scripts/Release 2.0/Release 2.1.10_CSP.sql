CREATE procedure [dbo].[getIdeasByProjectId]          
  @PROJIDS VARCHAR(MAX)           
as              
begin               
 select distinct I.*, 
 
 ABS(CEILING(CASE WHEN ([BEFORE_ERROR]) > 0 THEN (([BEFORE_ERROR]) -  ([AFTER_ERROR])) / ([BEFORE_ERROR]) 
	ELSE 0
	END * 100)) AS 'QUALITY_REDUCTION_OF_ERRORS',    
	
	ABS(CEILING(CASE WHEN ([BEFORE_LEAD_TIME]) > 0  THEN (([BEFORE_LEAD_TIME])  -  ([AFTER_LEAD_TIME])) / ([BEFORE_LEAD_TIME]) 
	ELSE 0
	END * 100)) AS 'REDUCTION_IN_LEAD_TIME',  

	CASE 
	
	WHEN BEFORE_LEAD_TIME_UOM = 1 THEN  
	CAST(ABS(CEILING(CASE WHEN ([BEFORE_LEAD_TIME]) > 0  THEN (([BEFORE_LEAD_TIME])  -  ([AFTER_LEAD_TIME])) / ([BEFORE_LEAD_TIME]) 
	ELSE 0
	END * 100)) AS VARCHAR(50)) + ' mins' 
	
	
	WHEN BEFORE_LEAD_TIME_UOM = 2 THEN  
	CAST(ABS(CEILING(CASE WHEN ([BEFORE_LEAD_TIME]) > 0  THEN (([BEFORE_LEAD_TIME])  -  ([AFTER_LEAD_TIME])) / ([BEFORE_LEAD_TIME]) 
	ELSE 0
	END * 100)) AS VARCHAR(50)) + ' hrs'

	WHEN BEFORE_LEAD_TIME_UOM = 3 THEN  
	CAST(ABS(CEILING(CASE WHEN ([BEFORE_LEAD_TIME]) > 0  THEN (([BEFORE_LEAD_TIME])  -  ([AFTER_LEAD_TIME])) / ([BEFORE_LEAD_TIME]) 
	ELSE 0
	END * 100)) AS VARCHAR(50)) + ' days'	
	
	END AS 'REDUCTION_IN_LEAD_TIME_DATA',

	ABS(CEILING(CASE WHEN ([BEFORE_CYCLE_TIME]) > 0  THEN (([BEFORE_CYCLE_TIME])  -  ([AFTER_CYCLE_TIME])) / ([BEFORE_CYCLE_TIME]) 
	ELSE 0
	END * 100)) AS 'REDUCTION_IN_CYCLE_TIME', 

	CASE 
	
	WHEN BEFORE_CYCLE_TIME_UOM = 1 THEN
	CAST(ABS(CEILING(CASE WHEN ([BEFORE_CYCLE_TIME]) > 0  THEN (([BEFORE_CYCLE_TIME])  -  ([AFTER_CYCLE_TIME])) / ([BEFORE_CYCLE_TIME]) 
	ELSE 0
	END * 100)) AS VARCHAR(50)) + ' mins'

	WHEN BEFORE_CYCLE_TIME_UOM = 2 THEN
	CAST(ABS(CEILING(CASE WHEN ([BEFORE_CYCLE_TIME]) > 0  THEN (([BEFORE_CYCLE_TIME])  -  ([AFTER_CYCLE_TIME])) / ([BEFORE_CYCLE_TIME]) 
	ELSE 0
	END * 100)) AS VARCHAR(50)) + ' hrs'


	WHEN BEFORE_CYCLE_TIME_UOM = 3 THEN
	CAST(ABS(CEILING(CASE WHEN ([BEFORE_CYCLE_TIME]) > 0  THEN (([BEFORE_CYCLE_TIME])  -  ([AFTER_CYCLE_TIME])) / ([BEFORE_CYCLE_TIME]) 
	ELSE 0
	END * 100)) AS VARCHAR(50)) + ' days'

	END AS 'REDUCTION_IN_CYCLE_TIME_DATA',

 ABS(CEILING((CUSTOMER_PERSONHOUR_SAVINGS))) AS 'SAVING_PER_YEAR_EFFORT',

 ABS(CEILING(CASE WHEN ([BEFORE_LEAD_TIME]) > 0  THEN (([BEFORE_EFFORT])  -  ([AFTER_EFFORT])) / ([BEFORE_EFFORT]) 
	ELSE 0
	END * 100)) AS 'AUTOMATION_INDEX', 

 ABS(CEILING((CAST(INTERNAL_SAVINGS AS NUMERIC(10, 2)))))  AS 'SAVINGS_IN_USD',
	ABS(CEILING((CUSTOMER_SAVINGS)))  AS 'HARD_BENEFITS',

ABS(CEILING((FINANCIAL_REVENUE))) AS 'REVENUE',
	ABS(CEILING((FINANCIAL_OPERATING_COST))) AS 'OPERATING_COST',
	ABS(CEILING((FINANCIAL_PROFITABILITY))) AS 'PROFITABILITY',
              
 P.CUST_ID, PP.PORTFOLIO_ID, PF.TITLE AS PORTFOLIO_NM, P.PROJ_NM              
 FROM PROJECT_INNOVATION I              
 INNER JOIN BAS_TEST.dbo.PROJECT P ON I.PROJECT_ID = P.PROJ_ID and  P.PROJ_ID IN (SELECT * FROM [DBO].[FN_SPLITSTRING](@PROJIDS,','))   AND  I.ISACTIVE = 1                   
 LEFT OUTER JOIN PORTFOLIO_PROJECT PP ON PP.PROJ_ID = P.PROJ_ID              
 LEFT OUTER JOIN PORTFOLIO PF ON PF.ID = PP.PORTFOLIO_ID              
              
 ORDER BY I.IDENTIFIED_DATE desc            
End




