CREATE procedure   
  getAllFindingsByTypeforCustomer  
  as   
  begin  
 with cte1 as  
    (select find.ID, find.FINDING_TYPE, find.FINDING_DESCRIPTION, exe.CUSTOMER_ID, exe.PROJECT_ID, find.created_date, ROW_NUMBER() over (partition by find.id order by find.audit_id) as rn1 from AUDIT_CHECKLIST_PROJECT_FINDINGS find  
  inner join AUDIT_CHECKLIST_PROJECT_EXECUTION exe on find.AUDIT_ID = exe.AUDIT_ID and find.ISACTIVE = 1 and find.issubmitted = 1 and exe.ISACTIVE = 1  
  where Month(find.created_date) = Month(GETDATE()) and YEAR(find.created_date) = YEAR(GETDATE())   
    
  )  
  
  select * from cte1 where rn1 = 1  
  end

GO

